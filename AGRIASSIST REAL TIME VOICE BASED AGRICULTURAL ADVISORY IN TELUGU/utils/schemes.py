# utils/schemes.py

def get_government_schemes(scheme="all"):
    """
    Rule-based government schemes information in Telugu
    """

    if scheme == "రైతు బంధు":
        return (
            "రైతు బంధు పథకం:\n"
            "• తెలంగాణ ప్రభుత్వం అందించే రైతు సంక్షేమ పథకం.\n"
            "• ప్రతి ఎకరాకు సాగు కోసం నగదు సహాయం అందుతుంది.\n"
            "• ఖరీఫ్ మరియు రబీ కాలాల్లో నేరుగా రైతు ఖాతాలో జమ చేస్తారు."
        )

    if scheme == "రైతు భీమా":
        return (
            "రైతు భీమా పథకం (ప్రధాన్ మంత్రి ఫసల్ భీమా యోజన):\n"
            "• పంట నష్టం జరిగితే భీమా కవరేజ్ అందుతుంది.\n"
            "• ప్రకృతి విపత్తుల నుండి రక్షణ.\n"
            "• తక్కువ ప్రీమియంతో రైతులకు భీమా సౌకర్యం."
        )

    if scheme == "పిఎం కిసాన్":
        return (
            "పిఎం కిసాన్ సమ్మాన్ నిధి:\n"
            "• కేంద్ర ప్రభుత్వ రైతు సంక్షేమ పథకం.\n"
            "• సంవత్సరానికి ₹6000 మూడు విడతలుగా అందిస్తారు.\n"
            "• నేరుగా రైతు ఖాతాలో జమ అవుతుంది."
        )

    if scheme == "మట్టి ఆరోగ్య కార్డు":
        return (
            "మట్టి ఆరోగ్య కార్డు పథకం:\n"
            "• నేలలో ఉన్న పోషక విలువల సమాచారం.\n"
            "• సరైన ఎరువుల వినియోగానికి సహాయం చేస్తుంది.\n"
            "• పంట దిగుబడి పెరుగుదలకు ఉపయోగపడుతుంది."
        )

    # 🔁 Default: list all schemes
    return (
        "ప్రధాన రైతు ప్రభుత్వ పథకాలు:\n\n"
        "1️ రైతు బంధు పథకం\n"
        "2️ పిఎం కిసాన్ సమ్మాన్ నిధి\n"
        "3️ రైతు భీమా (ప్రధాన్ మంత్రి ఫసల్ భీమా యోజన)\n"
        "4️ మట్టి ఆరోగ్య కార్డు పథకం\n\n"
        "మీకు ఏదైనా ప్రత్యేక పథకం గురించి తెలుసుకోవాలంటే అడగండి."
    )
