# utils/crop_advisory.py

def get_crop_advisory(crop=None):
    """
    Rule-based crop advisory in simple Telugu
    """

    if not crop:
        return (
            "దయచేసి పంట పేరు చెప్పండి.\n"
            "ఉదాహరణకు: మిర్చి సాగు సలహా, వరి సాగు సలహా."
        )

    if crop == "మిర్చి":
        return (
            "మిర్చి సాగు కోసం:\n"
            "• ప్రతి 7 రోజులకు ఒకసారి నీరు ఇవ్వాలి.\n"
            "• నాటిన 30 రోజులకు యూరియా 50 కిలోలు వేయాలి.\n"
            "• పురుగుల నివారణకు వారం రోజులకు ఒకసారి పరిశీలించాలి.\n"
            "• నీరు నిల్వ ఉండకుండా జాగ్రత్త పడాలి."
        )

    if crop == "వరి":
        return (
            "వరి సాగు కోసం:\n"
            "• పొలంలో ఎల్లప్పుడూ తడి ఉండేలా చూసుకోవాలి.\n"
            "• నాటిన 20–25 రోజులకు నత్రజని ఎరువులు వేయాలి.\n"
            "• కలుపు మొక్కలు తొలగించాలి.\n"
            "• పురుగులు కనిపిస్తే వెంటనే మందు పిచికారీ చేయాలి."
        )

    if crop == "పత్తి":
        return (
            "పత్తి సాగు కోసం:\n"
            "• ప్రతి 10–12 రోజులకు నీరు ఇవ్వాలి.\n"
            "• పూత దశలో ఫాస్పరస్ ఎరువులు ఉపయోగించాలి.\n"
            "• తెల్ల పురుగు నివారణకు జాగ్రత్తలు తీసుకోవాలి.\n"
            "• అధిక నీరు నిల్వ కాకుండా చూడాలి."
        )

    if crop == "మొక్కజొన్న":
        return (
            "మొక్కజొన్న సాగు కోసం:\n"
            "• ప్రతి 8–10 రోజులకు నీరు ఇవ్వాలి.\n"
            "• నాటిన 25 రోజులకు యూరియా వేయాలి.\n"
            "• కలుపు మొక్కలు తొలగించాలి.\n"
            "• ఆకులు పసుపు రంగు అయితే ఎరువు అవసరం."
        )

    return f"{crop} పంటకు సాగు సలహా ప్రస్తుతం అందుబాటులో లేదు."
